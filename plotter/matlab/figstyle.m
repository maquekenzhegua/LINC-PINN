function h = figstyle(w_mm, h_mm)
%FIGSTYLE White publication figure sized w_mm x h_mm with PINN4SOH-like defaults.
h = figure('Color','w','Visible','off','Units','pixels');
scr = get(h,'Position');
set(h,'Position',[scr(1) scr(2) round(w_mm/25.4*100) round(h_mm/25.4*100)]);
set(groot,'DefaultAxesFontName','Arial', ...
    'DefaultAxesFontSize',7, ...
    'DefaultTextFontName','Arial', ...
    'DefaultTextFontSize',7, ...
    'DefaultAxesLineWidth',0.6, ...
    'DefaultAxesBox','on', ...
    'DefaultAxesTickDir','out', ...
    'DefaultAxesTickLength',[0.012 0.012], ...
    'DefaultLineLineWidth',0.9, ...
    'DefaultLegendFontName','Arial', ...
    'DefaultLegendFontSize',6.5);
end
